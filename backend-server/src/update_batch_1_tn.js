async function updateBatch1() {
  console.log('Connecting to MongoDB Atlas...');
  await mongoose.connect(process.env.MONGODB_URI);
  const Scheme = mongoose.model('Scheme', new mongoose.Schema({}, { strict: false }));

  console.log('Applying Batch 1 verified Tamil schemes...');
  let updatedCount = 0;
  for (const s of batch1TnSchemes) {
    const res = await Scheme.updateOne(
      { schemeId: s.schemeId },
      {
        $set: {
          titleTa: s.titleTa,
          deptTa: s.deptTa,
          targetGroupTa: s.targetGroupTa,
          benefitDescTa: s.benefitDescTa,
          eligibilityTa: s.eligibilityTa,
          documentsTa: s.documentsTa
        }
      }
    );
    if (res.matchedCount > 0) {
      updatedCount++;
      console.log(`✓ [${s.schemeId}] ${s.titleTa}`);
    } else {
      console.warn(`⚠️ [${s.schemeId}] Not matched in database.`);
    }
  }

  console.log(`\nBatch 1 completed: ${updatedCount} / ${batch1TnSchemes.length} schemes updated.`);
  await mongoose.disconnect();
}

updateBatch1();
