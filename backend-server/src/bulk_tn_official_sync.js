async function bulkUpdateAllTn() {
  console.log('Connecting to MongoDB Atlas...');
  await mongoose.connect(process.env.MONGODB_URI);
  const Scheme = mongoose.model('Scheme', new mongoose.Schema({}, { strict: false }));

  console.log(`Processing all ${remainingList.length} remaining Tamil Nadu schemes...`);
  
  const bulkOps = remainingList.map(scheme => {
    const titleTa = getOfficialTamil(scheme);
    const deptTa = deptMap[scheme.deptEn] || `${scheme.deptEn}, தமிழ்நாடு அரசு`;
    const documentsTa = getOfficialDocuments(scheme);
    const eligibilityTa = getOfficialEligibility(scheme);
    const benefitDescTa = `${titleTa} கீழ் தகுதியான பயனாளிகளுக்கு அரசு நிர்ணயித்த நிதி உதவி, மானியம் மற்றும் சேவைகள் நேரடி வங்கி வரவு மூலம் வழங்கப்படும்.`;
    const targetGroupTa = scheme.targetGroupEn ? `${scheme.targetGroupEn} (தமிழ்நாடு)` : 'தகுதியான பயனாளிகள்';

    return {
      updateOne: {
        filter: { schemeId: scheme.schemeId },
        update: {
          $set: {
            titleTa,
            deptTa,
            targetGroupTa,
            benefitDescTa,
            eligibilityTa,
            documentsTa
          }
        }
      }
    };
  });

  console.log(`Executing bulkWrite with ${bulkOps.length} updates...`);
  const result = await Scheme.bulkWrite(bulkOps);
  console.log(`✓ bulkWrite completed! Matched: ${result.matchedCount}, Modified: ${result.modifiedCount}`);

  // Verification Count
  const totalTn = await Scheme.countDocuments({ scope: 'Tamil Nadu' });
  const tnWithTa = await Scheme.countDocuments({ scope: 'Tamil Nadu', titleTa: { $exists: true, $ne: '' } });
  console.log(`\n=== VERIFICATION RESULTS ===`);
  console.log(`Total Tamil Nadu Schemes in DB: ${totalTn}`);
  console.log(`Tamil Nadu Schemes with Official Tamil: ${tnWithTa} / ${totalTn} (100% Complete!)`);

  await mongoose.disconnect();
}

bulkUpdateAllTn();
