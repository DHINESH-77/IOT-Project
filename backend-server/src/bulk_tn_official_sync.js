// Generic Official Departmental Fallback Generator for any unlisted scheme
function getOfficialTamil(scheme) {
  const sId = scheme.schemeId;
  const mappedTitle = officialTitleMap[sId];
  if (mappedTitle) return mappedTitle;

  // Department-specific patterns
  const t = scheme.titleEn || '';
  if (t.includes('Scholarship') || t.includes('scholarship')) {
    return `${scheme.deptEn?.includes('Differently') ? 'மாற்றுத்திறனாளி' : 'மாணவர்களுக்கான'} கல்வி உதவித்தொகைத் திட்டம்`;
  }
  if (t.includes('Pension') || t.includes('pension')) {
    return 'சமூகப் பாதுகாப்பு மாதாந்திர ஓய்வூதியத் திட்டம்';
  }
  if (t.includes('Subsidy') || t.includes('subsidy')) {
    return `${t.split(' ')[0]} அரசு மானியத் திட்டம்`;
  }
  if (t.includes('Award') || t.includes('award')) {
    return 'தமிழ்நாடு அரசு சிறப்பு விருது மற்றும் பொற்கிழித் திட்டம்';
  }
  return scheme.titleTa || scheme.titleEn;
}

// Standard Official Document Set Generator
function getOfficialDocuments(scheme) {
  const d = scheme.deptEn || '';
  const docs = ['குடும்ப அட்டை (மின்னணு அட்டை)', 'ஆதார் அட்டை'];
  if (d.includes('Differently Abled')) {
    docs.push('மாற்றுத்திறனாளி தேசிய அடையாள அட்டை (UDID)');
    docs.push('மருத்துவச் சான்றிதழ்');
  } else if (d.includes('Agriculture')) {
    docs.push('பட்டா / சிட்டா (நில ஆவணங்கள்)');
    docs.push('விவசாயி பாஸ்புக் / உழவர் அட்டை');
  } else if (d.includes('Adi Dravidar') || d.includes('Backward')) {
    docs.push('சாதிச் சான்றிதழ்');
    docs.push('வருமானச் சான்றிதழ்');
  } else if (d.includes('MSME')) {
    docs.push('தொழில் திட்ட அறிக்கை (Project Report)');
    docs.push('உத்யாம் பதிவு சான்றிதழ் (Udyam)');
  }
  docs.push('வங்கிக் கணக்குப் புத்தகம்');
  return docs;
}

